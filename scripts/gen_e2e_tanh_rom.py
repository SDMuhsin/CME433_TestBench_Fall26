#!/usr/bin/env python3
"""Generate rtl/e2e_tanh_rom.v -- the hard-wired 256 x 15 b tanh pixel-threshold ROM
used by the dla_e2e_chip requant unit.

The G300 tanh output stage maps a 16-bit LUT index idx in [0, 32768] to an 8-bit
pixel via the Q20 tanh LUT (tb/data/g300_fp/g300_tanh_lut_fp.memh, 32769 x 24 b):

    pu(idx) = clamp(((LUT[idx] + 2^20) * 255 + 2^20) >> 21, 0, 255);  pix = pu - 128

pu() is monotone non-decreasing in idx, so it equals the number of thresholds
T[v] = min{idx : pu(idx) >= v} (v = 1..255) that are <= idx.  T[0] is defined
as 0.  The RTL finds pu by an 8-step binary search over T (largest v with
T[v] <= idx).  This script derives T from the LUT, proves the threshold form
exact for every idx, and emits the ROM as a synthesizable case statement.

Usage (repo root):  python3 scripts/gen_e2e_tanh_rom.py [--check-memh <thresholds.memh>]
"""
import argparse
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
LUT = REPO / 'tb/data/g300_fp/g300_tanh_lut_fp.memh'
OUT = REPO / 'rtl/e2e_tanh_rom.v'


def rd_signed(path, bits):
    out = []
    for tok in Path(path).read_text().split():
        v = int(tok, 16)
        out.append(v - (1 << bits) if (v >> (bits - 1)) & 1 else v)
    return out


def pu_of(lut_val):
    p = (((lut_val + (1 << 20)) * 255) + (1 << 20)) >> 21
    return max(0, min(255, p))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check-memh', help='optional thresholds memh to compare against')
    a = ap.parse_args()

    lut = rd_signed(LUT, 24)
    assert len(lut) == 32769, len(lut)
    pu = [pu_of(v) for v in lut]
    assert all(pu[i] <= pu[i + 1] for i in range(len(pu) - 1)), 'pu not monotone'
    T = [0] * 256
    for v in range(1, 256):
        T[v] = next(i for i, p in enumerate(pu) if p >= v)
    assert all(T[v] < (1 << 15) for v in range(256))

    # Exhaustive proof of the binary-search form used by the RTL.
    for idx in range(len(pu)):
        v = 0
        for b in range(7, -1, -1):
            if T[v | (1 << b)] <= idx:
                v |= 1 << b
        assert v == pu[idx], (idx, v, pu[idx])

    if a.check_memh:
        ref = [int(t, 16) for t in Path(a.check_memh).read_text().split()]
        assert ref == T, 'threshold table differs from ' + a.check_memh
        print('thresholds match', a.check_memh)

    lines = [
        '`timescale 1ns / 1ps',
        '',
        '// AUTO-GENERATED by scripts/gen_e2e_tanh_rom.py -- do not edit by hand.',
        '// Tanh pixel-threshold ROM for the dla_e2e_chip requant unit:',
        '//   T[v] = min{idx : pu(idx) >= v}, v = 1..255, T[0] = 0 (15-bit values),',
        '//   pu(idx) = clamp(((LUT[idx] + 2^20)*255 + 2^20) >> 21, 0, 255) over the',
        '//   Q20 tanh LUT tb/data/g300_fp/g300_tanh_lut_fp.memh.  Purely combinational.',
        'module e2e_tanh_rom (',
        '    input      [7:0]  v,',
        '    output reg [14:0] t',
        ');',
        '    always @* begin',
        '        case (v)',
    ]
    for v in range(256):
        lines.append(f"            8'd{v}: t = 15'd{T[v]};")
    lines += [
        "            default: t = 15'd0;",
        '        endcase',
        '    end',
        'endmodule',
        '',
    ]
    OUT.write_text('\n'.join(lines))
    print(f'wrote {OUT} (T[1]={T[1]} T[128]={T[128]} T[255]={T[255]})')


if __name__ == '__main__':
    main()
