#!/usr/bin/env python3
"""Generate rtl/fp16_tanh_rom.v: the 255 x 16-bit threshold ROM of dla_fp16_chip.

T[v] (v = 1..255) = smallest ordered FP16 key whose pixel is >= v, where
pixel(y) = clamp(floor((tanh(y)+1)*127.5 + 0.5), 0, 255) (float64, half-up) over every
legal FP16 y (normal or +0; FTZ'd/saturated codes never reach the tanh unit) and
key(y) = sign ? ~bits : bits | 0x8000.  The hardware pixel is #{v : key >= T[v]}.
Thresholds come from scripts/fp16_golden.py (checked exhaustively there).
usage: python3 scripts/gen_fp16_tanh_rom.py [out.v] [--memh out.memh]   (needs numpy only)
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import fp16_golden as g

R = Path(__file__).resolve().parent.parent
args = sys.argv[1:]
memh = None
if '--memh' in args:
    i = args.index('--memh'); memh = args[i + 1]; del args[i:i + 2]
out = Path(args[0]) if args else R / 'rtl/fp16_tanh_rom.v'
T = g.build_tanh_rom()
lines = ['`timescale 1ns / 1ps', '',
         '// fp16_tanh_rom -- GENERATED by scripts/gen_fp16_tanh_rom.py, do not edit.',
         '// 255 x 16 b threshold ROM: t = T[a] for a = 1..255 (a = 0 -> 0x0000, unused).',
         '// T[v] = smallest ordered FP16 key with pixel >= v, pixel(y) = clamp(floor((tanh(y)+1)*127.5+0.5),0,255).',
         'module fp16_tanh_rom (', '    input  wire [7:0]  a,', '    output reg  [15:0] t', ');',
         '    always @* begin', '        case (a)']
lines += [f"            8'd{v}: t = 16'h{int(T[v-1]):04x};" for v in range(1, 256)]
lines += ["            default: t = 16'h0000;", '        endcase', '    end', 'endmodule', '']
out.write_text('\n'.join(lines))
if memh: Path(memh).write_text(''.join(f'{int(t):04x}\n' for t in T))
print(f'wrote {out} (255 thresholds, T[1]={T[0]:04x} T[128]={T[127]:04x} T[255]={T[254]:04x})')
