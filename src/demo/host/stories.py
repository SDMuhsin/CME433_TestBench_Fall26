"""Demo stories from the bit-exact golden model + fixed-seed host sampler (no chip involved).

  python3 -m src.demo.host.stories [--out stories.json]
Each story starts from zero state, uses a fresh HostSampler(T=0.8, seed=0), and ends at
byte 0x00 (EOS) or when prompt + generated text reaches --max-bytes.
"""
import argparse
import json
from pathlib import Path

from src.golden.host.generate import generate
from src.golden.host.sampler import HostSampler
from src.golden.data.weights import load_params

PARAMS = 'src/golden/params/mamba_e96_fp16.npz'
PROMPTS = ('Once upon a time', 'Lily wanted', 'The little dog')
TEMPERATURE, SEED, MAX_BYTES = 0.8, 0, 200


def golden_story(cfg, P, prompt, max_bytes=MAX_BYTES):
    """-> full story text (prompt + generated bytes)."""
    text = generate(cfg, P, prompt, max_bytes - len(prompt), HostSampler(TEMPERATURE, SEED))
    return prompt + text.decode('ascii')


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--params', default=PARAMS)
    ap.add_argument('--max-bytes', type=int, default=MAX_BYTES)
    ap.add_argument('--out', type=Path, help='optional JSON {prompt: story}')
    a = ap.parse_args()
    cfg, P = load_params(a.params)
    stories = {p: golden_story(cfg, P, p, a.max_bytes) for p in PROMPTS}
    for p, s in stories.items():
        print(f'--- {p!r} ({len(s)} bytes)\n{s}\n')
    if a.out:
        a.out.write_text(json.dumps(stories, indent=1) + '\n')


if __name__ == '__main__':
    main()
