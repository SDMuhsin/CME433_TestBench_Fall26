"""Generate the NLU ROM RTL from the golden LUT tables (src/golden/arith/nlu.py).

Writes <out_dir>/mb_nlu_rom.v (340 x 16 b case ROM) and <out_dir>/mb_nlu_defs.vh (function
codes and ROM bases).  The address arithmetic in mb_nlu_addr.v hard-codes the grids, so this
script refuses to run if the golden grid parameters change.

usage: python3 -m src.scripts.gen_nlu_rom [out_dir]   (default src/rtl/nonlin)
"""
import sys
from pathlib import Path

from src.golden.arith.nlu import EXP2, FRAC_BITS, FUNCS, ROM, ROM_WORDS, RSQRT, SIGMOID, SOFTPLUS

HEADER = '// Generated by src/scripts/gen_nlu_rom.py from src/golden/arith/nlu.py -- do not edit.\n'
GRIDS = {  # what mb_nlu_addr.v implements: (mode, lo, k, segments)
    'sigmoid': ('uniform', -8.0, 3, 128), 'softplus': ('uniform', -8.0, 3, 128),
    'exp2': ('exp2', 0.0, 5, 32), 'rsqrt': ('rsqrt', 1.0, 4, 48)}


def check_grids():
    assert FRAC_BITS == 11 and FUNCS == (SIGMOID, SOFTPLUS, EXP2, RSQRT)
    for fn in FUNCS:
        assert (fn.mode, fn.lo, fn.k, fn.segments) == GRIDS[fn.name], f'{fn.name} grid changed'


def rom_v():
    rows = '\n'.join(f"            9'd{a}: t = 16'h{int(w):04x};" for a, w in enumerate(ROM))
    return f"""{HEADER}`timescale 1ns / 1ps

// ============================================================================
// mb_nlu_rom -- shared nonlinear-unit table, {ROM_WORDS} x 16 b FP16 (spec section 4).
// Combinational read.  Layout (word bases in mb_nlu_defs.vh):
{chr(10).join(f'//   {fn.name:8s} {fn.base:3d} .. {fn.base + fn.segments:3d}' for fn in FUNCS)}
// ============================================================================
module mb_nlu_rom (
    input  wire [8:0]  addr,
    output reg  [15:0] t
);
    always @* begin
        case (addr)
{rows}
            default: t = 16'h0000;
        endcase
    end
endmodule
"""


def defs_vh():
    codes = ', '.join(f"NLU_{fn.name.upper()} = 2'd{c}" for c, fn in enumerate(FUNCS))
    bases = ', '.join(f"NLU_BASE_{fn.name.upper()} = 9'd{fn.base}" for fn in FUNCS)
    return f'{HEADER}// NLU function codes and ROM word bases.\nlocalparam [1:0] {codes};\n' \
           f'localparam [8:0] {bases};\n'


def main(out_dir):
    check_grids()
    out = Path(out_dir)
    (out / 'mb_nlu_rom.v').write_text(rom_v())
    (out / 'mb_nlu_defs.vh').write_text(defs_vh())


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / 'rtl/nonlin')
