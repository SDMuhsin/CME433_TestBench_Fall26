"""Assemble the mb_chip microcode and write its RTL.

Writes <out_dir>/mb_ucode_rom.v (case ROM, one disassembled uop per line) and
<out_dir>/mb_ucode_defs.vh (field positions, op/source/mode codes, entry points, stream length).

usage: python3 -m src.ucode.gen_rom [out_dir]   (default src/rtl/seq)
"""
import sys
from pathlib import Path

from src.golden.data.stream import stream_words

from .isa import EPS_BITS, MODES, OPS, SRCS, UOP_W, decode, disasm, field_positions
from .program import CHIP_CFG, build

HEADER = '// Generated by src/ucode/gen_rom.py from src/ucode/program.py -- do not edit.\n'


def pc_width(n):
    return max(1, (n - 1).bit_length())


def rom_v(words, entries):
    pw = pc_width(len(words))
    names = {v: k for k, v in entries.items()}
    rows = []
    for a, w in enumerate(words):
        if a in names:
            rows.append(f'            // ---- entry {names[a]}')
        rows.append(f"            {pw}'d{a}: uop = {UOP_W}'h{w:09x};  // {disasm(decode(w))}")
    return f"""{HEADER}`timescale 1ns / 1ps

// ============================================================================
// mb_ucode_rom -- sequencer microcode, {len(words)} x {UOP_W} b (combinational read).
// ISA: src/ucode/isa.py; program: src/ucode/program.py.
// ============================================================================
module mb_ucode_rom (
    input  wire [{pw - 1}:0]  pc,
    output reg  [{UOP_W - 1}:0] uop
);
    always @* begin
        case (pc)
{chr(10).join(rows)}
            default: uop = {UOP_W}'h{OPS.index('END') << field_positions()['op'][0]:09x};  // END
        endcase
    end
endmodule
"""


def defs_vh(words, entries):
    pw = pc_width(len(words))
    pos = field_positions()
    lines = [HEADER + '// Microcode word layout, codes and entry points.',
             f'localparam integer UOP_W = {UOP_W}, UPC_W = {pw};',
             'localparam integer ' + ', '.join(f'F_{n.upper()} = {p}' for n, (p, _) in pos.items()) + ';',
             'localparam [2:0] ' + ', '.join(f"OP_{o} = 3'd{i}" for i, o in enumerate(OPS)) + ';',
             'localparam [2:0] ' + ', '.join(f"SRC_{s} = 3'd{i}" for i, s in enumerate(SRCS)) + ';',
             'localparam [1:0] ' + ', '.join(f"MODE_{m} = 2'd{i}" for i, m in enumerate(MODES)) + ';',
             'localparam [UPC_W-1:0] ' + ', '.join(f"ENTRY_{n.upper()} = {pw}'d{a}"
                                                    for n, a in entries.items()) + ';',
             f"localparam [15:0] EPS_BITS = 16'h{EPS_BITS:04x};",
             f'localparam integer TOKEN_BYTES = {2 * stream_words(CHIP_CFG)};']
    return '\n'.join(lines) + '\n'


def main(out_dir):
    p = build()
    words = p.words()
    out = Path(out_dir)
    (out / 'mb_ucode_rom.v').write_text(rom_v(words, p.entries))
    (out / 'mb_ucode_defs.vh').write_text(defs_vh(words, p.entries))


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / 'rtl/seq')
