"""Exhaustive check RTL == Python model (65,536 inputs) and error metrics of the structured
multipliers.

  python3 -m src_gan_tsmc65.approx.check [variant ...]
Signed variants (variants.py): the iverilog table of bench/variants/<v>.v (bench/mul_table.py)
against the Python netlist model; metrics over all inputs and over b >= 0 (the chip's
layers 2-3 multiply by non-negative activations). Also the unsigned paper designs in
approx/rtl/. Writes approx/results/variants_error.md.
"""
import subprocess
import sys
from pathlib import Path

import numpy as np

from ..bench.mul_table import mul8_table
from ..common.paths import BUILD
from . import vk2017
from .metrics import table_stats
from .variants import VARIANTS

HERE = Path(__file__).resolve().parent
R = np.arange(-128, 128)
A, B = np.meshgrid(R, R, indexing='ij')
U = np.arange(256)
AU, BU = np.meshgrid(U, U, indexing='ij')


def unsigned_rtl_table(vfile, work):
    work.mkdir(parents=True, exist_ok=True)
    img = work / 'tb_mul8u.vvp'
    subprocess.run(['iverilog', '-g2012', '-o', str(img), str(HERE / 'tb' / 'tb_mul8u_table.v'),
                    str(vfile)], check=True)
    out = subprocess.run(['vvp', '-n', str(img)], check=True, capture_output=True, text=True).stdout
    return np.array([int(w, 16) for w in out.split() if len(w) == 4], np.int64).reshape(256, 256)


def signed_row(v):
    py = VARIANTS[v]().products(A, B).reshape(256, 256)
    rtl = mul8_table(v, BUILD / 'approx' / v)
    same = int((py == rtl).sum())
    ex = A * B
    s, p = table_stats(rtl, ex, max_out=1 << 14), table_stats(rtl, ex, B >= 0, max_out=1 << 14)
    return (f'| `{v}` | {same}/65536 | {s["MED"]:.2f} / {s["bias"]:+.2f} | '
            f'{p["MED"]:.2f} / {p["bias"]:+.2f} | {s["max_abs"]} | {100 * s["ER"]:.2f} % | '
            f'{s["MRED"]:.2e} | {s["NMED"]:.2e} |'), same == 65536


def unsigned_row(tag, fn):
    py = fn(8).products(AU, BU).reshape(256, 256)
    rtl = unsigned_rtl_table(HERE / 'rtl' / f'vk2017_{tag}_u8.v', BUILD / 'approx' / tag)
    same = int((py == rtl).sum())
    s = table_stats(rtl, AU * BU)
    return (f'| `vk2017_{tag}_u8` (unsigned) | {same}/65536 | {s["MED"]:.2f} / {s["bias"]:+.2f} | '
            f'- | {s["max_abs"]} | {100 * s["ER"]:.2f} % | {s["MRED"]:.2e} | {s["NMED"]:.2e} |'), \
        same == 65536


def main():
    names = sys.argv[1:] or list(VARIANTS)
    rows = ['| Variant | RTL == Python | MAE / bias, all | MAE / bias, b >= 0 | max abs error | '
            'error rate | MRED | NMED |', '|---' * 8 + '|']
    ok = True
    for v in names:
        row, good = signed_row(v)
        rows.append(row)
        ok &= good
        print(row, flush=True)
    if not sys.argv[1:]:
        for tag, fn in (('m1', vk2017.multiplier1), ('m2', vk2017.multiplier2)):
            row, good = unsigned_row(tag, fn)
            rows.append(row)
            ok &= good
            print(row, flush=True)
        out = HERE / 'results' / 'variants_error.md'
        out.parent.mkdir(exist_ok=True)
        out.write_text('# Structured multipliers: exhaustive RTL check and error metrics\n\n'
                       'Generated by `python3 -m src_gan_tsmc65.approx.check`. Signed variants: '
                       'NMED = MED / 2^14.\n\n' + '\n'.join(rows) + '\n')
    print('PASS' if ok else 'FAIL')
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()
