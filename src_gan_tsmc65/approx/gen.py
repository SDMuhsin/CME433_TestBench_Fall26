"""Write the generated Verilog of the structured multipliers.

  python3 -m src_gan_tsmc65.approx.gen
    bench/variants/<v>.v          signed gan_mul8 variants of variants.py
    approx/rtl/vk2017_m{1,2}_u8.v unsigned 8 x 8 Multiplier1 / Multiplier2 of the paper (vk_mul8u)
The files are generated; edit the Python and regenerate.
"""
from pathlib import Path

from . import vk2017
from .emit import verilog
from .variants import VARIANTS

HERE = Path(__file__).resolve().parent
BENCH = HERE.parent / 'bench' / 'variants'
GEN = 'Generated by python3 -m src_gan_tsmc65.approx.gen (do not edit).'

ABOUT = {
    'bw_exact': ['bw_exact: signed 8 x 8 Baugh-Wooley multiplier, Dadda tree of exact half /',
                 'full adders, one carry-propagate adder. Structured exact baseline of bw_axfa6.'],
    'bw_axfa6': ['bw_axfa6: bw_exact with the approximate half / full adders of Venkatachalam &',
                 'Ko (IEEE TVLSI 2017, eqs. 2-3) in the 6 least significant columns.'],
    'booth_exact': ['booth_exact: signed 8 x 8 radix-4 Booth multiplier (b recoded, 4 rows of',
                    '9 bits + neg bits, sign extension by constant), Dadda tree of exact half /',
                    'full adders, one carry-propagate adder. Structured exact baseline of booth_axfa5.'],
    'booth_axfa5': ['booth_axfa5: booth_exact with the approximate half / full adders of',
                    'Venkatachalam & Ko (IEEE TVLSI 2017, eqs. 2-3) in the 5 least significant columns.'],
}


def cells_line(m):
    return 'Reduction cells: ' + ', '.join(f'{k} x{v}' for k, v in sorted(m.cell_count().items()))


def main():
    for v, fn in VARIANTS.items():
        m = fn()
        head = ABOUT[v] + ['a = weight, b = activation, p = a * b (signed, 16 bit).',
                           cells_line(m), GEN]
        (BENCH / f'{v}.v').write_text(verilog(m, 'gan_mul8', head))
        print(BENCH / f'{v}.v')
    (HERE / 'rtl').mkdir(exist_ok=True)
    for tag, fn, what in (('m1', vk2017.multiplier1, 'Multiplier1 (approximate in all columns)'),
                          ('m2', vk2017.multiplier2, 'Multiplier2 (approximate in columns 0..6)')):
        m = fn(8)
        head = [f'Venkatachalam & Ko, IEEE TVLSI 25(5) 2017: unsigned 8 x 8 {what},',
                'altered partial products (eq. 1), OR-ed generate signals, approximate HA / FA /',
                '4:2 compressor (eqs. 2-4), Fig. 2 reduction, exact final adder.',
                cells_line(m), GEN]
        f = HERE / 'rtl' / f'vk2017_{tag}_u8.v'
        f.write_text(verilog(m, 'vk_mul8u', head, signed=False))
        print(f)


if __name__ == '__main__':
    main()
