"""N x N -> 2N multipliers of the standalone multiplier bench (syn/mulbench/,
docs/papers/mul16_feasibility.md), one registry for N = 8 and N = 16.

  python3 -m src_gan_tsmc65.approx.mulbench --width 16    writes syn/mulbench/rtl/w16/<design>.v
Every file defines module `mul_core` (a, b: N bits, p: 2N bits), wrapped by syn/mulbench/mul_bench.v.

Unsigned designs (the papers' own hardware tables): exact, the carry-disregard multipliers of
Amirafshar 2023 (CDM8_xy at 8 bits, CDM16_wxyz at 16), DR-ALM-5/6 of Yin 2021. Signed designs:
exact, the HAM of Shi 2025 (8 bits: HAM-A H7C0; 16 bits: the H9C1 family of Table IV) and the
signed counterparts of the chip's 8-bit cdm_* / dralm_* / ham_ae sign schemes. At N = 8 the
signed rows are the chip variants (same generators, module renamed). `paper` = the paper's own
savings vs its exact multiplier of the same width, (area, power, delay) in %.
"""
import argparse
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from . import cdm, cdm16_v, dralm, dralm_v, ham, ham_v
from .emit import verilog as netlist_verilog

HERE = Path(__file__).resolve().parent
RTL = HERE.parent / 'syn' / 'mulbench' / 'rtl'
GEN = 'Generated by python3 -m src_gan_tsmc65.approx.mulbench (do not edit).'
MOD = 'mul_core'


class Exact:
    def __init__(self, n, signed):
        self.n, self.signed = n, signed

    def products(self, a, b):
        return np.asarray(a, np.int64) * np.asarray(b, np.int64)


def exact_v(n, signed, header):
    s = 'signed ' if signed else ''
    return '\n'.join(['`timescale 1ns / 1ps', ''] + [f'// {h}' for h in header] + [
        f'module {MOD} (',
        f'    input  wire {s}[{n - 1}:0] a,',
        f'    input  wire {s}[{n - 1}:0] b,',
        f'    output wire {s}[{2 * n - 1}:0] p',
        ');',
        '    assign p = a * b;',
        'endmodule', ''])


@dataclass(frozen=True)
class Design:
    name: str
    signed: bool
    about: str
    model: object                # products(a, b)
    rtl: object                  # header lines -> Verilog text
    paper: tuple = None          # (area %, power %, delay %) vs the paper's exact multiplier
    base: str = ''               # that baseline


def _pct(x, ref):
    return tuple(round(100 * (v / r - 1), 1) for v, r in zip(x, ref))


# the papers' hardware numbers (area um^2, power uW, delay ns), 45 nm Nangate
CDM_T4 = {'exact': (300.6, 85.61, 0.76), (5, 1): (269.2, 78.071, 0.641), (7, 3): (237.5, 70.826, 0.563)}
CDM_T5 = {'exact': (1348.4, 501.4, 1.35), '0000': (1318.6, 479.9, 1.03),
          'f880': (990.6, 365.1, 0.77), 'fbb3': (905.7, 335.1, 0.77)}
YIN_T6 = {'exact': (1377, 641.3, 1.51), 5: (452.7, 77.5, 0.80), 6: (541.0, 96.5, 0.80),
          'sexact': (2647, 634.0, 1.02), 's5': (624.8, 128.2, 1.06), 's6': (656.0, 149.0, 1.00)}
SHI_T4 = {'exact': (2563, 1394, 1.75), 'H9C1': (1318, 616, 1.34), 'H9C1-SP': (1265, 593, 1.34),
          'H9C1-SO': (1105, 534, 1.33)}
B_CDM8 = 'Exact8 (two exact 8 x 4 arrays), Table IV'
B_CDM = 'Exact16 (four exact 8-bit arrays), Table V'
B_YIN = 'exact unsigned 16-bit, Table 6'
B_YINS = 'exact Booth 16-bit, Table 6'
B_SHI = 'exact radix-4 Booth, 500 MHz, Table IV'


def _netlist(m, signed):
    return lambda h: netlist_verilog(m, MOD, h, signed=signed)


def _cdm(n):
    if n == 8:
        out = []
        for xy in ((5, 1), (7, 3)):
            tag = f'{xy[0]:x}{xy[1]:x}'
            m = cdm.cdm(*xy, mode='unsigned')
            out.append(Design(f'u_cdm{tag}', False, f'CDM8_{tag} (Amirafshar 2023, Table I)', m,
                              _netlist(m, False), _pct(CDM_T4[xy], CDM_T4['exact']), B_CDM8))
        for xy in ((5, 1), (7, 3)):
            tag = f'{xy[0]:x}{xy[1]:x}'
            m = cdm.cdm(*xy)
            out.append(Design(f's_cdm{tag}', True, f'CDM8_{tag}, sign-magnitude (= chip cdm_{tag})',
                              m, _netlist(m, True)))
        return out
    out = [Design(f'u_cdm{d}', False, f'CDM16_{d} (Amirafshar 2023, Fig. 5 / Table II)', cdm.Cdm16(d),
                  lambda h, d=d: cdm16_v.verilog(d, h), _pct(CDM_T5[d], CDM_T5['exact']), B_CDM)
           for d in ('0000', 'f880', 'fbb3')]
    out += [Design(f's_cdm{d}', True, f'CDM16_{d}, sign-magnitude (the chip cdm_* scheme)',
                   cdm.Cdm16(d, signed=True), lambda h, d=d: cdm16_v.verilog(d, h, signed=True))
            for d in ('f880', 'fbb3')]
    return out


def _dralm(n):
    out = []
    for t in (5, 6):
        out.append(Design(f'u_dralm{t}', False, f'unsigned DR-ALM-{t} (Yin 2021)',
                          dralm.Dralm(n, t, 'none', False),
                          lambda h, t=t: dralm_v.verilog(t, 'none', h, MOD, n),
                          _pct(YIN_T6[t], YIN_T6['exact']) if n == 16 else None,
                          B_YIN if n == 16 else ''))
    for t in (5, 6):
        out.append(Design(f's_dralm{t}', True, f'signed DR-ALM-{t}, paper sign units (Yin 2021'
                          + (', = chip dralm_t%d)' % t if n == 8 else ')'), dralm.Dralm(n, t, 'paper'),
                          lambda h, t=t: dralm_v.verilog(t, 'paper', h, MOD, n),
                          _pct(YIN_T6[f's{t}'], YIN_T6['sexact']) if n == 16 else None,
                          B_YINS if n == 16 else ''))
    return out


def _ham(n):
    if n == 8:
        hams = (('s_hama', None, ham.HAM8['A'], 'HAM-A H7C0, PACC + SC (= chip ham_a)'),
                ('s_hamae', None, ham.HAM8['A'].with_(me='exact'), 'HAM-A, exact magnitudes (= chip ham_ae)'))
    else:
        hams = (('s_h9c1', 'H9C1', ham.H9C1, 'H9C1, PACC + SC + BCT (paper; the chip ham_a scheme)'),
                ('s_h9c1sp', 'H9C1-SP', ham.PAPER16['H9C1-SP'], 'H9C1-SP, OC + SC, SP output (paper)'),
                ('s_h9c1so', 'H9C1-SO', ham.PAPER16['H9C1-SO'], 'H9C1-SO, OC + SC, SO output (paper)'),
                ('s_h9c1e', None, ham.H9C1.with_(me='exact'),
                 'H9C1 with exact magnitudes (ablation, the chip ham_ae scheme)'))
    return [Design(name, True, about + ' (Shi 2025)', h,
                   lambda hd, h=h, name=name: ham_v.verilog(h, name, hd, MOD),
                   _pct(SHI_T4[key], SHI_T4['exact']) if key else None, B_SHI if key else '')
            for name, key, h, about in hams]


def designs(n):
    """name -> Design for operand width n (8 or 16)."""
    assert n in (8, 16)
    d = [Design('u_exact', False, 'exact unsigned a * b (DesignWare)', Exact(n, False),
                lambda h: exact_v(n, False, h))]
    m = cdm.cdm(1, 1, mode='unsigned', n=n)
    d.append(Design('u_dadda', False, 'exact unsigned AND array, Dadda tree, one CPA (structured '
                    'exact twin of the CDMs)', m, _netlist(m, False)))
    d += [x for x in _cdm(n) if not x.signed] + [x for x in _dralm(n) if not x.signed]
    d.append(Design('s_exact', True, 'exact signed a * b (DesignWare)', Exact(n, True),
                    lambda h: exact_v(n, True, h)))
    d += _ham(n) + [x for x in _cdm(n) if x.signed] + [x for x in _dralm(n) if x.signed]
    return {x.name: x for x in d}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--width', type=int, default=16, choices=(8, 16))
    n = ap.parse_args().width
    out = RTL / f'w{n}'
    out.mkdir(parents=True, exist_ok=True)
    for x in designs(n).values():
        kind = 'signed' if x.signed else 'unsigned'
        head = [f'{MOD} {x.name}: {kind} {n} x {n} -> {2 * n}, {x.about}.',
                'Reference model: approx/mulbench.py.', GEN]
        f = out / f'{x.name}.v'
        f.write_text(x.rtl(head))
        print(f)


if __name__ == '__main__':
    main()
