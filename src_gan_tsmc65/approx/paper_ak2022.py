"""Error metrics of the Aizaz & Khare 2022 TACBM (signed 16 x 16) vs the paper's Tables III-IV.

  python3 -m src_gan_tsmc65.approx.paper_ak2022 [--samples 10000000] [--jobs 40]
Uniform random signed operands in [-32768, 32767] like the paper (10 M pairs, fixed seed);
NMED = MED / 2^30 (2^(2N-2), Sec. III). Writes approx/results/ak2022_error.md.
"""
import argparse
from pathlib import Path

from .exhaustive import signed_stats
from .tacbm import tacbm

ALL = None
# (w, terms) -> paper (MRED in %, NMED in 1e-5[, NoEB, PRED %]); Table IV for all terms,
# Table III for subsets (terms = () is "0(w)": truncation without compensation).
PAPER = {
    (4, ALL): (0.011, 0.507, 18.85, 99.96), (6, ALL): (0.012, 0.551, 18.85, 99.94),
    (8, ALL): (0.014, 0.567, 18.83, 99.93), (10, ALL): (0.023, 0.619, 18.72, 99.86),
    (12, ALL): (0.041, 0.839, 18.47, 99.81),
    (8, (1,)): (0.016, 0.587), (8, (2,)): (0.015, 0.586), (8, ()): (0.019, 0.596),
    (10, (1, 2)): (0.028, 0.628), (10, (2, 3)): (0.033, 0.715), (10, (1, 3)): (0.032, 0.759),
    (10, (1,)): (0.035, 0.823), (10, (2,)): (0.031, 0.711), (10, (3,)): (0.034, 0.839),
    (10, ()): (0.043, 0.864),
    (12, (1, 2, 3)): (0.044, 0.957), (12, (2, 3, 4)): (0.046, 0.966),
    (12, (1, 3, 4)): (0.054, 0.958), (12, (1, 2, 4)): (0.044, 0.895),
    (12, (1, 2)): (0.042, 1.061), (12, (1, 3)): (0.046, 0.961), (12, (1, 4)): (0.046, 1.011),
    (12, (2, 3)): (0.055, 1.115), (12, (2, 4)): (0.058, 1.124), (12, (3, 4)): (0.059, 1.110),
    (12, (1,)): (0.055, 1.085), (12, (2,)): (0.067, 1.302), (12, (3,)): (0.064, 1.281),
    (12, (4,)): (0.065, 1.338), (12, ()): (0.068, 1.342),
}
OUT = Path(__file__).resolve().parent / 'results' / 'ak2022_error.md'


def _name(w, terms):
    if terms is None:
        return f'TACBM w={w}, all terms'
    return f'w={w}, ' + (', '.join(f't{k}' for k in terms) if terms else 'no compensation')


def _cmp(ours, paper):
    return f'{ours:.3f} / {paper:.3f} ({100 * (ours / paper - 1):+.0f} %)'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--samples', type=int, default=10_000_000)
    ap.add_argument('--jobs', type=int, default=40)
    ap.add_argument('--w', type=int, nargs='+', default=[4, 6, 8, 10, 12])
    args = ap.parse_args()
    rows = ['| Design | MRED % (ours / paper) | NMED 1e-5 (ours / paper) | NoEB (ours / paper) | '
            'PRED % (ours / paper) | ER | bias | max abs ED |', '|---' * 8 + '|']
    ref = signed_stats(tacbm, 16, (16, 0, None, True), jobs=args.jobs, samples=args.samples)
    rows.append(f'| Booth + neg-OR only (w=0) | {100 * ref["MRED"]:.4f} | {1e5 * ref["NMED"]:.3f} | '
                f'{ref["NoEB"]:.2f} | {100 * ref["PRED"]:.2f} | {ref["ER"]:.4f} | '
                f'{ref["bias"]:.4g} | {ref["max_abs"]} |')
    print(rows[-1], flush=True)
    for (w, terms), p in PAPER.items():
        if w not in args.w:
            continue
        r = signed_stats(tacbm, 16, (16, w, terms, True), jobs=args.jobs, samples=args.samples)
        noeb = f'{r["NoEB"]:.2f} / {p[2]:.2f}' if len(p) > 2 else f'{r["NoEB"]:.2f} / -'
        pred = f'{100 * r["PRED"]:.2f} / {p[3]:.2f}' if len(p) > 2 else f'{100 * r["PRED"]:.2f} / -'
        rows.append(f'| {_name(w, terms)} | {_cmp(100 * r["MRED"], p[0])} | '
                    f'{_cmp(1e5 * r["NMED"], p[1])} | {noeb} | {pred} | {r["ER"]:.4f} | '
                    f'{r["bias"]:.4g} | {r["max_abs"]} |')
        print(rows[-1], flush=True)
    rows += ['', '8 x 8 (exhaustive, NMED = MED / 2^14; the paper only states "MRED of 0.02 on w=6", '
             'Sec. IV):', '', '| Design | MRED | NMED | ER | bias | max abs ED |', '|---' * 6 + '|']
    for w in (0, 4, 6, 8):
        r = signed_stats(tacbm, 8, (8, w), jobs=args.jobs)
        rows.append(f'| TACBM 8-bit w={w} | {r["MRED"]:.4f} | {r["NMED"]:.2e} | {r["ER"]:.4f} | '
                    f'{r["bias"]:.2f} | {r["max_abs"]} |')
        print(rows[-1], flush=True)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text('# Aizaz & Khare 2022 (TACBM): error metrics vs the paper\n\n'
                   f'Generated by `python3 -m src_gan_tsmc65.approx.paper_ak2022` '
                   f'({args.samples:,} uniform random signed 16-bit pairs, seed fixed). '
                   'Paper values: Table IV (all terms) and Table III (subsets).\n\n'
                   + '\n'.join(rows) + '\n')


if __name__ == '__main__':
    main()
