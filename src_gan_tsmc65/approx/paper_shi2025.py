"""Error metrics of the Shi et al. 2025 hybrid approximate multipliers (HAM) vs the paper.

  python3 -m src_gan_tsmc65.approx.paper_shi2025 [--jobs 32] [--fit]
- Algorithm 1 worked example (H6L9, A = 16'h050a, B = 16'hfef2 -> 31'h7ffac1e0).
- Table III: the six 16-bit designs of Table II (biases of Table I) on the paper's grid, a, b in
  -2^15 .. 2^15 - 1 with step 8 (8192^2 pairs). MRED averages RED = |E| / max(1, |exact|) over
  all pairs, NMED = MED / 2^30, "RED < 2 % / 5 %" over all pairs. Plus interpretation ablations.
- Table V: 8-bit HAM-A/B/C (H7C0), unsigned exhaustive, NMED = MED / 255^2; the paper prints no
  8-bit biases, ours come from `fit` (--fit reruns it). Then the signed gan_mul8 variants.
Writes approx/results/shi2025_error.md.
"""
import argparse
from pathlib import Path

import numpy as np

from . import ham
from .exhaustive import signed_stats, unsigned_stats
from .variants import VARIANTS

OUT = Path(__file__).resolve().parent / 'results' / 'shi2025_error.md'
# Table III: MRED %, NMED 1e-3, RED < 2 % (%), RED < 5 % (%)
T3 = {'H6L9': (1.30, 3.109, 78.95, 99.05), 'H6L9-SP': (1.38, 3.113, 77.87, 98.52),
      'H6L9-SO': (1.41, 3.113, 77.85, 98.49), 'H9C1': (0.68, 1.642, 96.21, 99.997),
      'H9C1-SP': (0.72, 1.642, 95.59, 99.77), 'H9C1-SO': (0.72, 1.642, 95.87, 99.85)}
ABL16 = {'H9C1, OC magnitudes': ham.H9C1.with_(me='oc'),
         'H9C1, exact magnitudes': ham.H9C1.with_(me='exact'),
         'H6L9, LOA in X1 only': ham.H6L9.with_(loa='x1'),
         'H6L9, LOA in p1_PWL only': ham.H6L9.with_(loa='p1')}
# Table V (8 bit): NMED 1e-3, MRED %
T5 = {'A': (2.7, 1.29), 'B': (3.0, 1.42), 'C': (3.3, 1.57)}


def _c(ours, paper, fmt):
    return f'{ours:{fmt}} / {paper:{fmt}} ({100 * (ours / paper - 1):+.1f} %)'


def algorithm1():
    a, b = 0x050a, 0xfef2 - (1 << 16)
    p = int(ham.H6L9.products([a], [b])[0])
    return p, 0x7ffac1e0 - (1 << 31), a * b


def row16(name, h, jobs, paper=None):
    s = signed_stats(ham.build, 16, (h,), jobs, max_out=1 << 30, step=8)
    nz = s['n'] - 2 * 8192 + 1                       # pairs with a non-zero product
    allp = lambda frac: 100 * (frac * nz + s['n'] - nz) / s['n']   # zero products: RED 0
    ours = (100 * s['MRED_all'], 1e3 * s['NMED'], allp(s['PRED']), allp(s['PRED5']))
    if paper:
        cells = [_c(o, p, f) for o, p, f in zip(ours, paper, ('.3f', '.3f', '.2f', '.3f'))]
    else:
        cells = [f'{o:{f}}' for o, f in zip(ours, ('.3f', '.3f', '.2f', '.3f'))]
    return f'| {name} | ' + ' | '.join(cells) + ' |'


def mred8(h, a, b):
    ex = a * b
    return np.mean(np.abs(h.products(a, b) - ex) / np.maximum(1, np.abs(ex)))


def fit(h, sweeps=6):
    """Coordinate descent of the five biases (+-1..3 LSB) minimising the unsigned 8-bit MRED."""
    u = np.arange(256)
    a, b = (x.ravel() for x in np.meshgrid(u, u, indexing='ij'))
    best, bias = mred8(h, a, b), list(h.biases)
    for _ in range(sweeps):
        moved = False
        for i in range(5):
            for d in (-3, -2, -1, 1, 2, 3):
                t = bias.copy()
                t[i] += d
                v = mred8(h.with_(biases=tuple(t)), a, b)
                if v < best - 1e-12:
                    best, bias, moved = v, t, True
        if not moved:
            break
    return h.with_(biases=tuple(bias))


def table5(jobs, refit):
    rows = ['| Design | X2 / X4 bits | biases (1/32) | NMED (1e-3) ours / paper | MRED (%) ours / paper |',
            '|---|---|---|---|---|']
    for k, (pn, pm) in T5.items():
        h = ham.HAM8[k].with_(signed=False)
        if refit:
            h = fit(h.with_(biases=(32, 24, 24, 32, 4)))
        s = unsigned_stats(ham.build, 8, (h,), jobs)
        rows.append(f'| HAM-{k} | {h.x2b} / {h.x4b} | {"/".join(map(str, h.biases))} | '
                    f'{_c(1e3 * s["NMED"], pn, ".3f")} | {_c(100 * s["MRED_all"], pm, ".3f")} |')
        print(rows[-1], flush=True)
    return rows


def signed8(jobs):
    rows = ['| Variant | ME | MRED (%) | NMED (1e-3, / 2^14) | MAE / bias | max abs error | RED < 2 % |',
            '|---|---|---|---|---|---|---|']
    for v in ('ham_a', 'ham_c', 'ham_ae'):
        h = VARIANTS[v]()
        s = signed_stats(ham.build, 8, (h,), jobs)
        rows.append(f'| `{v}` | {h.me} | {100 * s["MRED_all"]:.3f} | {1e3 * s["NMED"]:.3f} | '
                    f'{s["MED"]:.2f} / {s["bias"]:+.2f} | {s["max_abs"]} | {100 * s["PRED"]:.2f} % |')
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--jobs', type=int, default=32)
    ap.add_argument('--fit', action='store_true', help='refit the 8-bit biases')
    a = ap.parse_args()
    p, want, ex = algorithm1()
    lines = ['# Shi et al. 2025 (HAM): error metrics vs the paper', '',
             'Generated by `python3 -m src_gan_tsmc65.approx.paper_shi2025`. Cells: ours / paper '
             '(relative gap).', '',
             f'Algorithm 1 (H6L9, A = 1290, B = -270): model {p}, paper 31\'h7ffac1e0 = {want}, '
             f'exact {ex}: {"equal" if p == want else "DIFFERENT"}.', '',
             '## Table III: 16 bit, grid step 8 (Table I biases, Table II ME / MTS / SHIFT)', '',
             '| Design | MRED (%) | NMED (1e-3) | RED < 2 % (%) | RED < 5 % (%) |', '|---|---|---|---|---|']
    for name, h in ham.PAPER16.items():
        lines.append(row16(name, h, a.jobs, T3[name]))
        print(lines[-1], flush=True)
    lines += ['', 'Interpretation ablations (not in the paper):', '',
              '| Design | MRED (%) | NMED (1e-3) | RED < 2 % (%) | RED < 5 % (%) |', '|---|---|---|---|---|']
    for name, h in ABL16.items():
        lines.append(row16(name, h, a.jobs))
        print(lines[-1], flush=True)
    lines += ['', '## Table V: 8-bit H7C0 HAM-A/B/C, unsigned exhaustive', ''] + table5(a.jobs, a.fit)
    lines += ['', '## Signed 8 x 8 gan_mul8 variants (exhaustive, MRED over all pairs)', ''] + signed8(a.jobs)
    OUT.write_text('\n'.join(lines) + '\n')
    print(OUT)


if __name__ == '__main__':
    main()
