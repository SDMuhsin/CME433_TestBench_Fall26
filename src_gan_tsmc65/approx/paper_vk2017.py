"""Exhaustive error metrics of the Venkatachalam & Ko 2017 multipliers vs the paper (Table VI).

  python3 -m src_gan_tsmc65.approx.paper_vk2017 [--n 8 16] [--jobs 40]
writes src_gan_tsmc65/approx/results/vk2017_error.md (n = 16: 2^32 pairs, ~7 min per design
on 40 cores). The paper reports MRE and NED for n = 16 only.
"""
import argparse
from pathlib import Path

from . import vk2017
from .exhaustive import unsigned_stats

PAPER = {('Multiplier1', 16): (7.63e-2, 1.78e-2), ('Multiplier2', 16): (2.44e-4, 7.10e-6)}
OUT = Path(__file__).resolve().parent / 'results' / 'vk2017_error.md'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--n', type=int, nargs='+', default=[8, 16])
    ap.add_argument('--jobs', type=int, default=40)
    args = ap.parse_args()
    rows = ['| Design | n | ER | MRED | NMED (MED / max product) | NED (MED / max ED) | '
            'bias | max abs ED | paper MRE | paper NED |', '|---' * 10 + '|']
    for n in args.n:
        for name, fn in (('Multiplier1', vk2017.multiplier1), ('Multiplier2', vk2017.multiplier2)):
            r = unsigned_stats(fn, n, (n,), jobs=args.jobs)
            p = PAPER.get((name, n))
            ref = f'{p[0]:.3g} | {p[1]:.3g}' if p else '- | -'
            rows.append(f'| {name} | {n} | {r["ER"]:.4f} | {r["MRED"]:.3e} | {r["NMED"]:.3e} | '
                        f'{r["NED"]:.3e} | {r["bias"]:.4g} | {r["max_abs"]} | {ref} |')
            print(rows[-1], flush=True)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text('# Venkatachalam & Ko 2017: exhaustive error metrics (unsigned)\n\n'
                   'Generated by `python3 -m src_gan_tsmc65.approx.paper_vk2017`.\n\n'
                   + '\n'.join(rows) + '\n')


if __name__ == '__main__':
    main()
