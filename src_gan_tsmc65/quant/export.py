"""Write a quantised generator as the chip's model directory (model/fmnist_w<D>/) and the CSR
reset header rtl/cfg/w<D>/g300_quant_params.vh."""
import json

import numpy as np

from ..common.memh import write_memh
from ..golden.latents import quant_z
from ..golden.model import CSR_NAMES, forward
from . import reference

REF_SEEDS = range(8)


def write_weights(out, m, width):
    for n in (0, 2, 4):
        write_memh(out / f'G300_{n}_weight.memh', m[f'W{n}'], bits=width)
        write_memh(out / f'G300_{n}_bias.memh', m[f'b{n}'], bits=width)


def write_csr(out, m):
    """24 bytes: MA0, MB0, MA2, MB2, MW4, MB4 as 32-bit little endian (CSR 0x10 .. 0x27)."""
    write_memh(out / 'csr.memh', [(m[k] >> (8 * i)) & 0xFF for k in CSR_NAMES for i in range(4)])


def ref_latent(seed):
    import torch
    return torch.randn(1, 64, generator=torch.Generator().manual_seed(seed)).double().numpy()


def write_refs(out, m, sz, width):
    """ref_vectors/seed_<s>/{zq,expected}.memh; expected from the plain-integer reference model,
    which must agree with the vectorised golden model."""
    for s in REF_SEEDS:
        zq = quant_z(ref_latent(s), sz, width)[0]
        pix = reference.pixels(zq, m)
        assert (np.asarray(pix) == forward(zq, m)['pix'][0]).all(), f'reference != golden, seed {s}'
        d = out / 'ref_vectors' / f'seed_{s}'
        d.mkdir(parents=True, exist_ok=True)
        write_memh(d / 'zq.memh', zq, bits=width)
        write_memh(d / 'expected.memh', pix)


def write_header(path, m, width):
    lines = [f'// AUTO-GENERATED by python3 -m src_gan_tsmc65.quant.build --width {width} -- do not edit by hand.',
             f'// int{width} requantization constants (CSR reset values) of the Fashion-MNIST G300 pipeline.',
             f'localparam integer G300_REQ_SHIFT    = {m["S"]};',
             f'localparam integer G300_REQ_SHIFT_L4 = {m["S"]};']
    lines += [f'localparam signed [63:0] G300_{k} = 64\'sd{m[k]};' for k in CSR_NAMES]
    path.write_text('\n'.join(lines) + '\n')


def write_json(out, m, sc, clip, width, extra):
    q = dict(width=width, weight_clip_ratio=clip,
             calibration=dict(method='static, p99.99', n_latents=512, cal_seed=1000,
                              sZ=sc['sZ'], sH0=sc['sH0'], sH2=sc['sH2']),
             scales={k: v for k, v in sc.items() if '_' in k}, S=m['S'],
             csr={k: dict(addr=hex(0x10 + 4 * i), value=m[k], hex=f'0x{m[k]:08x}') for i, k in enumerate(CSR_NAMES)},
             **extra)
    (out / 'quant.json').write_text(json.dumps(q, indent=1) + '\n')
