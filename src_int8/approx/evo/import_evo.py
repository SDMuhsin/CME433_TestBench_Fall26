"""Import EvoApproxLib-Lite signed 8 x 8 multipliers as mq_mul8 variants.

python3 -m src_int8.approx.evo.import_evo <evoapproxlib clone> <id> [...]     e.g. 1KR8 1L2H
-> src_int8/bench/variants/evo_<id>/{mul8s_<id>.v (unmodified copy, licence header kept),
   mq_mul8.v (wrapper: A = weight a, B = activation b), LICENSE (the library's MIT licence)}
The library: https://github.com/ehw-fit/evoapproxlib; Mrazek, Sekanina, Vasicek, IEEE JETCAS
10(4), 2020. The published metrics of each circuit are in the header of its file.
"""
import shutil
import sys
from pathlib import Path

VAR = Path(__file__).resolve().parents[2] / 'bench/variants'

WRAP = '''`timescale 1ns / 1ps

// evo_{id} -- EvoApproxLib signed 8 x 8 multiplier mul8s_{id} (mul8s_{id}.v, MIT licence, see
// LICENSE) as mq_mul8: A = weight a, B = activation b. Generated by src_int8.approx.evo.import_evo.
module mq_mul8 (
    input  wire signed [7:0]  a,
    input  wire signed [7:0]  b,
    output wire signed [15:0] p
);
    mul8s_{id} u_mul (.A(a), .B(b), .O(p));
endmodule
'''


def main():
    lib, ids = Path(sys.argv[1]), sys.argv[2:]
    for i in ids:
        src = next(p for p in sorted(lib.glob(f'multiplers/8x8_signed/*/mul8s_{i}.v')))
        d = VAR / f'evo_{i}'
        d.mkdir(parents=True, exist_ok=True)
        shutil.copy(src, d / src.name)
        shutil.copy(lib / 'LICENSE.md', d / 'LICENSE')
        (d / 'mq_mul8.v').write_text(WRAP.format(id=i))
        print(f'{src} -> {d}')


if __name__ == '__main__':
    main()
