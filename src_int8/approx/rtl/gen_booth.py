"""Generate a structural exact signed 8 x 8 radix-4 Booth multiplier: the activation b is
Booth-encoded (4 digits in {-2..2}), the weight a is the multiplicand; Dadda reduction and final
adder as in gen_dadda. It is the second structural exact baseline of the approximate-multiplier
comparison.

Partial products: row i (weight 4^i) is d_i * a as 9 bits, pp_j = (one & a_j | two & a_(j-1)) ^ neg,
plus neg at its LSB. neg is gated to 0 for the digit 0 (b bits 111), so a zero digit gives an
all-zero row (low activity for small negative activations). Sign extension: the row's sign bit
is inverted and the constant -sum_i 2^(8+2i) mod 2^16 = 0xAB00 is added.

python3 -m src_int8.approx.rtl.gen_booth  -> src_int8/bench/variants/exact_booth.v
"""
from pathlib import Path

from .gen_dadda import module_text

N = 8
OUT = Path(__file__).resolve().parents[2] / 'bench/variants/exact_booth.v'
CONST = (-sum(1 << (N + 2 * i) for i in range(N // 2))) % (1 << 2 * N)


def encoder():
    """Booth encoder wires one_i, two_i, neg_i for the 4 digits of b"""
    lines = []
    for i in range(N // 2):
        hi, mid, lo = f'b[{2 * i + 1}]', f'b[{2 * i}]', (f'b[{2 * i - 1}]' if i else "1'b0")
        lines += [f'    wire one{i} = {mid} ^ {lo};',
                  f'    wire two{i} = ({hi} & ~{mid} & ~{lo}) | (~{hi} & {mid} & {lo});',
                  f'    wire neg{i} = {hi} & ~({mid} & {lo});']
    return '\n'.join(lines) + '\n'


def ppm():
    """Booth partial products per column (Verilog expressions)"""
    cols = [[] for _ in range(2 * N)]
    a = lambda j: f'a[{min(j, N - 1)}]'
    for i in range(N // 2):
        for j in range(N + 1):
            sel = f'(one{i} & {a(j)})' + (f' | (two{i} & {a(j - 1)})' if j else '')
            e = f'(({sel}) ^ neg{i})'
            c = 2 * i + j
            if c < 2 * N:
                cols[c].append(f'~{e}' if j == N else e)
        cols[2 * i].append(f'neg{i}')
    for c in range(2 * N):
        if CONST >> c & 1:
            cols[c].append("1'b1")
    return cols


def main():
    OUT.write_text(module_text('''// exact_booth -- structural exact signed 8 x 8 radix-4 Booth multiplier (b Booth-encoded,
// zero-digit-gated negation, inverted-sign-bit sign extension, Dadda reduction with {fa} full and
// {ha} half adders, final carry-propagate adder). Exact baseline of the approximate-multiplier
// study; generated by src_int8.approx.rtl.gen_booth (do not edit). Same ports and function as
// src_int8/rtl/int/mq_mul8.v.''', ppm(), encoder()))
    print(f'-> {OUT}')


if __name__ == '__main__':
    main()
