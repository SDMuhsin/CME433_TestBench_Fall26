"""Generate a structural exact signed 8 x 8 multiplier: Baugh-Wooley partial products, Dadda
reduction with full / half adders, final carry-propagate adder. It is the structural exact
baseline of the approximate-multiplier comparison (the C-SSM paper's exact reference is a
Dadda multiplier).

python3 -m src_int8.approx.rtl.gen_dadda  -> src_int8/bench/variants/exact_dadda.v
"""
from pathlib import Path

N = 8
OUT = Path(__file__).resolve().parents[2] / 'bench/variants/exact_dadda.v'


def ppm():
    """Baugh-Wooley partial products per column (Verilog expressions); constants 1 at 2^n, 2^(2n-1)"""
    cols = [[] for _ in range(2 * N)]
    for i in range(N):
        for j in range(N):
            e = f'a[{i}] & b[{j}]'
            cols[i + j].append(f'~({e})' if (i == N - 1) ^ (j == N - 1) else f'({e})')
    cols[N].append("1'b1")
    cols[2 * N - 1].append("1'b1")
    return cols


def dadda(cols):
    """Dadda reduction to height 2: -> (instance lines, wire decls, two final rows)"""
    d = [2]
    while d[-1] < max(map(len, cols)):
        d.append(d[-1] * 3 // 2)
    insts, wires, k = [], [], 0
    for target in reversed(d[:-1]):
        new = [[] for _ in range(2 * N + 1)]
        carry_in = [0] * (2 * N + 1)
        for c in range(2 * N):
            bits, ns = list(cols[c]), 0
            while len(bits) + ns + carry_in[c] > target and len(bits) >= 2:
                excess = len(bits) + ns + carry_in[c] - target
                s, co = f's{k}', f'c{k}'
                wires += [s, co]
                if excess >= 2 and len(bits) >= 3:
                    x, y, z = bits[:3]; bits = bits[3:]
                    insts.append(f'    mq_fa u{k} (.x({x}), .y({y}), .z({z}), .s({s}), .c({co}));')
                else:
                    x, y = bits[:2]; bits = bits[2:]
                    insts.append(f'    mq_ha u{k} (.x({x}), .y({y}), .s({s}), .c({co}));')
                new[c].append(s); new[c + 1].append(co); carry_in[c + 1] += 1; ns += 1; k += 1
            new[c] = bits + new[c]
        cols = [new[c] for c in range(2 * N)]
    assert max(map(len, cols)) <= 2
    rows = [[col[r] if r < len(col) else "1'b0" for col in cols] for r in range(2)]
    return insts, wires, rows


CELLS = """module mq_fa (input wire x, y, z, output wire s, c);
    assign s = x ^ y ^ z;
    assign c = (x & y) | (z & (x ^ y));
endmodule

module mq_ha (input wire x, y, output wire s, c);
    assign s = x ^ y;
    assign c = x & y;
endmodule
"""


def module_text(header, cols, pre=''):
    """mq_mul8 source: header comment lines (use {fa}/{ha} for the adder counts), optional
    preamble statements (e.g. encoder wires), Dadda tree over cols, final adder"""
    insts, wires, rows = dadda(cols)
    row = lambda r: '{' + ', '.join(reversed(r)) + '}'
    hdr = header.format(fa=sum('mq_fa' in i for i in insts), ha=sum('mq_ha' in i for i in insts))
    return f'''`timescale 1ns / 1ps

{hdr}
{CELLS}
module mq_mul8 (
    input  wire signed [7:0]  a,
    input  wire signed [7:0]  b,
    output wire signed [15:0] p
);
{pre}    wire {', '.join(wires)};
{chr(10).join(insts)}
    wire [15:0] r0 = {row(rows[0])};
    wire [15:0] r1 = {row(rows[1])};
    assign p = r0 + r1;
endmodule
'''


def main():
    OUT.write_text(module_text('''// exact_dadda -- structural exact signed 8 x 8 multiplier (Baugh-Wooley partial products,
// Dadda reduction with {fa} full and {ha} half adders, final carry-propagate adder).
// Exact baseline of the approximate-multiplier study; generated by src_int8.approx.rtl.gen_dadda
// (do not edit). Same ports and function as src_int8/rtl/int/mq_mul8.v.''', ppm()))
    print(f'-> {OUT}')


if __name__ == '__main__':
    main()
