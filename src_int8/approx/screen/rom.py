"""Write a screening model as a ROM-based mq_mul8 (simulation only) for the emulator / bench.

python3 -m src_int8.approx.screen.rom <model> [...]   (models: src_int8/approx/screen/models.py)
-> build/approx/screen/<model>.v + <model>.hex; then
   python3 -m src_int8.bench.emu.run build/approx/screen/<model>.v build/bench/c512x1024 --n 128
"""
import sys
from pathlib import Path

from ..err.metrics import metrics
from .models import MODELS

OUT = Path(__file__).resolve().parents[3] / 'build/approx/screen'


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name in sys.argv[1:]:
        t = MODELS[name]()
        (OUT / f'{name}.hex').write_text(''.join(f'{v & 0xffff:04x}\n' for v in t.ravel()))
        (OUT / f'{name}.v').write_text(
            '// screening ROM (simulation only), generated by src_int8.approx.screen.rom\n'
            'module mq_mul8 (input wire signed [7:0] a, input wire signed [7:0] b,\n'
            '                output wire signed [15:0] p);\n'
            '    reg [15:0] rom [0:65535];\n'
            f'    initial $readmemh("{OUT / name}.hex", rom);\n'
            "    assign p = rom[{a ^ 8'h80, b ^ 8'h80}];\n"
            'endmodule\n')
        m = metrics(t)
        print(f'{name}: MED {m["MED"]:.2f} NMED {m["NMED"]:.3e} MRED {m["MRED"]:.3e} bias {m["bias"]:+.3f} '
              f'-> {OUT / name}.v')


if __name__ == '__main__':
    main()
