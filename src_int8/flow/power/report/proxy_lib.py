#!/usr/bin/env python3
"""Proxy Liberty for the flip-flops the gf180mcu_as_sc_mcu7t3v3 Liberty models without power.

The AS 3V3 Liberty has internal_power only for combinational cells and NO cell has leakage, so
OpenSTA reports 0 internal power for the 672 flip-flops (their CLK-pin and Q-switching energy)
and 0 std-cell leakage.  To bound that gap, this writes a library with the GF180 7-track 5 V
library's flops at its 3.3 V corner (gf180mcu_fd_sc_mcu7t5v0__<pvt>.lib, same process and
supply, a different cell design) renamed to the AS cell/pin names:
    dfxtp_2 <- dffq_2,  dfxtp_4 <- dffq_4,  dfsrtp_2 <- dffrsnq_2 (pin SETN -> SN)
report/power.tcl (PROXY_LIB=...) replace_cells the flops onto it, so these three cells take their power
(internal + leakage) from the proxy.  It is an estimate, not signoff data.

usage: proxy_lib.py <fd_sc_mcu7t5v0 .lib> <out .lib>
"""
import re
import sys

MAP = {
    "gf180mcu_as_sc_mcu7t3v3__dfxtp_2": ("gf180mcu_fd_sc_mcu7t5v0__dffq_2", {}),
    "gf180mcu_as_sc_mcu7t3v3__dfxtp_4": ("gf180mcu_fd_sc_mcu7t5v0__dffq_4", {}),
    "gf180mcu_as_sc_mcu7t3v3__dfsrtp_2": ("gf180mcu_fd_sc_mcu7t5v0__dffrsnq_2", {"SETN": "SN"}),
}


def group(text, start):
    """text[start] is inside 'cell(...) {': return the end index of the matching '}'"""
    i = text.index("{", start)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return j + 1
    raise SystemExit("unbalanced braces")


def main():
    src, dst = sys.argv[1:3]
    text = open(src).read()
    first = re.search(r"\n\s*cell\s*\(", text).start()
    head = re.sub(r"library\s*\(\s*[^)]*\)", "library(mq_flop_power_proxy)", text[:first], count=1)
    cells = []
    for as_name, (fd_name, ren) in MAP.items():
        m = re.search(r"cell\s*\(\s*\"?%s\"?\s*\)" % re.escape(fd_name), text)
        if not m:
            raise SystemExit("no %s in %s" % (fd_name, src))
        body = text[m.start():group(text, m.start())]
        body = body.replace(fd_name, as_name)
        for a, b in ren.items():
            body = re.sub(r"\b%s\b" % a, b, body)
        cells.append("  " + body)
    with open(dst, "w") as f:
        f.write("/* GENERATED by src_int8/flow/power/report/proxy_lib.py from %s: power proxy only */\n" % src)
        f.write(head + "\n" + "\n".join(cells) + "\n}\n")
    print("proxy_lib: %d flop cells -> %s" % (len(cells), dst))


if __name__ == "__main__":
    main()
