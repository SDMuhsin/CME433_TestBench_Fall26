"""Generate the NLU ROM collateral from the golden LUT tables (src_int8/golden/ops/nlu.py).

Writes
  <rtl_dir>/mq_nlu_rom.v        340 x 16 b unsigned case ROM (default src_int8/rtl/nonlin)
  <rtl_dir>/mq_nlu_defs.vh      function codes, ROM word bases, segment counts
  <params_dir>/nlu_rom.hex      one 4-digit hex word per line (readmemh), default golden/params

The address arithmetic of spec 5.1 is hard-coded in the RTL (mq_nlu_addr), so this script
refuses to run if the golden table layout changes.

usage: python3 -m src_int8.scripts.gen_nlu_rom [rtl_dir] [params_dir]
"""
import sys
from pathlib import Path

from ..golden.ops.nlu import EXP2, FRAC_BITS, FUNCS, ROM, ROM_WORDS, RSQRT, SIGMOID, SOFTPLUS

HEADER = '// Generated by src_int8/scripts/gen_nlu_rom.py from src_int8/golden/ops/nlu.py -- do not edit.\n'
LAYOUT = {'sigmoid': (0, 128), 'softplus': (129, 128), 'exp2': (258, 32), 'rsqrt': (291, 48)}
HERE = Path(__file__).resolve().parents[1]


def check_layout():
    assert FRAC_BITS == 11 and FUNCS == (SIGMOID, SOFTPLUS, EXP2, RSQRT) and ROM_WORDS == 340
    for fn in FUNCS:
        assert (fn.base, fn.segments) == LAYOUT[fn.name], f'{fn.name} layout changed'


def rom_v():
    rows = '\n'.join(f"            9'd{a}: t = 16'h{int(w):04x};" for a, w in enumerate(ROM))
    layout = '\n'.join(f'//   {fn.name:8s} {fn.base:3d} .. {fn.end - 1:3d}' for fn in FUNCS)
    return f"""{HEADER}`timescale 1ns / 1ps

// ============================================================================
// mq_nlu_rom -- shared nonlinear-unit table, {ROM_WORDS} x 16 b unsigned (spec 5.1).
// Combinational read.  Layout (word bases in mq_nlu_defs.vh):
{layout}
// ============================================================================
module mq_nlu_rom (
    input  wire [8:0]  addr,
    output reg  [15:0] t
);
    always @* begin
        case (addr)
{rows}
            default: t = 16'h0000;
        endcase
    end
endmodule
"""


def defs_vh():
    codes = ', '.join(f"NLU_{fn.name.upper()} = 2'd{c}" for c, fn in enumerate(FUNCS))
    bases = ', '.join(f"NLU_BASE_{fn.name.upper()} = 9'd{fn.base}" for fn in FUNCS)
    segs = ', '.join(f"NLU_SEG_{fn.name.upper()} = 8'd{fn.segments}" for fn in FUNCS)
    return (f'{HEADER}// NLU function codes, ROM word bases and segment counts.\n'
            f'localparam [1:0] {codes};\nlocalparam [8:0] {bases};\nlocalparam [7:0] {segs};\n'
            f'localparam NLU_FRAC_BITS = {FRAC_BITS};\n')


def rom_hex():
    return ''.join(f'{int(w):04x}\n' for w in ROM)


def main(rtl_dir, params_dir):
    check_layout()
    rtl, params = Path(rtl_dir), Path(params_dir)
    rtl.mkdir(parents=True, exist_ok=True)
    params.mkdir(parents=True, exist_ok=True)
    (rtl / 'mq_nlu_rom.v').write_text(rom_v())
    (rtl / 'mq_nlu_defs.vh').write_text(defs_vh())
    (params / 'nlu_rom.hex').write_text(rom_hex())
    print(f'wrote {rtl / "mq_nlu_rom.v"}, {rtl / "mq_nlu_defs.vh"}, {params / "nlu_rom.hex"} ({ROM_WORDS} words)')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else HERE / 'rtl' / 'nonlin',
         sys.argv[2] if len(sys.argv) > 2 else HERE / 'golden' / 'params')
