"""Spec-formula reference of the shared LUT unit (spec.md section 5.1): ROM contents, address
arithmetic and the four functions, exact integers only.

`write_rom` writes the image as rtl/nonlin/mq_nlu_rom.memh (one hex word per line); the RTL
ROM itself (mq_nlu_rom.v) is generated by team A's scripts/gen_nlu_rom.py from golden/ops/nlu.py
and tb/run_unit.sh checks it word for word against this module.
"""
import math

from .intmath import rsh, sat

FRAC = 1 << 11                       # interpolation fraction scale
BASE = {'sigmoid': 0, 'softplus': 129, 'exp2': 258, 'rsqrt': 291}
SEGS = {'sigmoid': 128, 'softplus': 128, 'exp2': 32, 'rsqrt': 48}
FN_CODE = {'sigmoid': 0, 'softplus': 1, 'exp2': 2, 'rsqrt': 3}
ROM_WORDS = 340


def _round(x):
    return math.floor(x + 0.5)


def build_rom():
    rom = [0] * ROM_WORDS
    for j in range(129):
        x = -8.0 + j / 8.0
        rom[BASE['sigmoid'] + j] = _round(2 ** 15 / (1.0 + math.exp(-x)))
        rom[BASE['softplus'] + j] = min(_round(math.log1p(math.exp(x)) * 2 ** 12), 32767)
    for j in range(33):
        rom[BASE['exp2'] + j] = _round(2 ** (j / 32.0) * 2 ** 14)
    for j in range(49):
        rom[BASE['rsqrt'] + j] = _round(2 ** 14 / math.sqrt(1.0 + j / 16.0))
    assert all(0 <= w <= 0xFFFF for w in rom) and rom[BASE['exp2'] + 32] == 32768
    return rom


ROM = build_rom()


def write_rom(path):
    with open(path, 'w') as f:
        f.write('// mq_nlu_rom contents, 340 x 16 b unsigned (spec.md 5.1), one word per line.\n'
                '// sigmoid 0..128, softplus 129..257, exp2 258..290, rsqrt 291..339.\n')
        for w in ROM:
            f.write(f'{w:04x}\n')


def address(fn, x):
    """fn, INT32/UINT32 input -> dict(i, f, sh, zero).  i is the function-local segment."""
    if fn in ('sigmoid', 'softplus'):
        x = max(-2048, min(2048, x))
        u = x + 2048
        i = min(u >> 5, 127)
        f = (u - 32 * i) << 6
        return dict(i=i, f=f, sh=11, zero=0)
    if fn == 'exp2':
        if x >= 0:
            x = 0
        if x <= -16 << 19:
            return dict(i=0, f=0, sh=10, zero=1)
        e = x >> 19
        frac = x & ((1 << 19) - 1)
        return dict(i=frac >> 14, f=(frac >> 3) & 0x7FF, sh=10 - e, zero=0)
    assert fn == 'rsqrt'
    n = x & 0xFFFFFFFF
    assert n >= 16, 'rsqrt input must be >= 16'
    b = n.bit_length() - 1
    E = b - 16
    if E & 1:
        E -= 1
    m16 = n >> E if E >= 0 else n << -E
    u = m16 - (1 << 16)
    assert (1 << 16) <= m16 < (1 << 18) and 0 <= u >> 12 <= 47
    return dict(i=u >> 12, f=(u >> 1) & 0x7FF, sh=16 + E // 2, zero=0)


def lerp(fn, a):
    """Sigma = T[i] (2^11 - f) + T[i+1] f on the lane (two steps, ps 0)."""
    idx = BASE[fn] + a['i']
    return ROM[idx] * (FRAC - a['f']) + ROM[idx + 1] * a['f']


def evaluate(fn, x):
    """Full unit: INT16 result (0 when the exp2 zero flag is set)."""
    a = address(fn, x)
    return 0 if a['zero'] else sat(rsh(lerp(fn, a), a['sh']), 16)


def sigmoid(x):
    return evaluate('sigmoid', x)


def softplus(x):
    return evaluate('softplus', x)


def exp2(p):
    return evaluate('exp2', p)


def rsqrt(n):
    return evaluate('rsqrt', n)


def silu16(x, sh):
    """SiLU-type product sat_16(rsh(x * sigmoid(x), sh)) for Q7.8 x."""
    return sat(rsh(x * sigmoid(x), sh), 16)
