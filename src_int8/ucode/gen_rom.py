"""Assemble the mq_chip microcode and write its RTL.

Writes <out_dir>/mq_ucode_rom.v (case ROM, one disassembled uop per line) and
<out_dir>/mq_ucode_defs.vh (field positions, op / source / mode codes, entry points, stream length).

usage: python3 -m src_int8.ucode.gen_rom [out_dir]   (default src_int8/rtl/seq)
"""
import sys
from pathlib import Path

from .isa import EPS_VAL, MWS, NLU_FNS, OPS, SRCS, UOP_W, WMODES, WWS, decode, disasm, field_positions
from .program import STREAM_BYTES, build

HEADER = '// Generated by src_int8/ucode/gen_rom.py from src_int8/ucode/program.py -- do not edit.\n'
HEX_W = (UOP_W + 3) // 4


def pc_width(n):
    return max(1, (n - 1).bit_length())


def rom_v(words, entries):
    pw = pc_width(len(words))
    names = {v: k for k, v in entries.items()}
    rows = []
    for a, w in enumerate(words):
        if a in names:
            rows.append(f'            // ---- entry {names[a]}')
        rows.append(f"            {pw}'d{a}: uop = {UOP_W}'h{w:0{HEX_W}x};  // {disasm(decode(w))}")
    end = OPS.index('END') << field_positions()['op'][0]
    return f"""{HEADER}`timescale 1ns / 1ps

// ============================================================================
// mq_ucode_rom -- sequencer microcode, {len(words)} x {UOP_W} b (combinational read).
// ISA: src_int8/ucode/isa.py; program: src_int8/ucode/program.py.
// ============================================================================
module mq_ucode_rom (
    input  wire [{pw - 1}:0]  pc,
    output reg  [{UOP_W - 1}:0] uop
);
    always @* begin
        case (pc)
{chr(10).join(rows)}
            default: uop = {UOP_W}'h{end:0{HEX_W}x};  // END
        endcase
    end
endmodule
"""


def defs_vh(words, entries):
    pw = pc_width(len(words))
    pos = field_positions()
    lines = [HEADER + '// Microcode word layout, codes and entry points.',
             f'localparam integer UOP_W = {UOP_W}, UPC_W = {pw};',
             'localparam integer ' + ', '.join(f'F_{n.upper()} = {p}' for n, (p, _) in pos.items()) + ';',
             'localparam [2:0] ' + ', '.join(f"OP_{o} = 3'd{i}" for i, o in enumerate(OPS)) + ';',
             'localparam [2:0] ' + ', '.join(f"SRC_{s} = 3'd{i}" for i, s in enumerate(SRCS)) + ';',
             'localparam [1:0] ' + ', '.join(f"WM_{m} = 2'd{i}" for i, m in enumerate(WMODES)) + ';',
             'localparam [1:0] ' + ', '.join(f"WW_{w} = 2'd{i}" for i, w in enumerate(WWS)) + ';',
             'localparam [1:0] ' + ', '.join(f"MW_{w} = 2'd{i}" for i, w in enumerate(MWS)) + ';',
             'localparam [1:0] ' + ', '.join(f"NLU_{f.upper()} = 2'd{i}" for i, f in enumerate(NLU_FNS)) + ';',
             'localparam [UPC_W-1:0] ' + ', '.join(f"ENTRY_{n.upper()} = {pw}'d{a}"
                                                    for n, a in entries.items()) + ';',
             f"localparam [31:0] EPS_VAL = 32'd{EPS_VAL};",
             f'localparam integer TOKEN_BYTES = {STREAM_BYTES};']
    return '\n'.join(lines) + '\n'


def main(out_dir):
    p = build()
    words = p.words()
    assert len(words) < 256, 'the PC CSR is 8 bits'
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / 'mq_ucode_rom.v').write_text(rom_v(words, p.entries))
    (out / 'mq_ucode_defs.vh').write_text(defs_vh(words, p.entries))


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / 'rtl/seq')
